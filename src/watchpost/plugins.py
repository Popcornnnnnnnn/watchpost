"""Scaffolding and conformance checking for external Watchpost channel and notifier plugins."""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
from pathlib import Path
from typing import Any, Literal

from watchpost.adapters.external_plugin import ExternalCommandAdapter
from watchpost.config import ExternalAdapterConfig, ExternalNotifierConfig
from watchpost.models import ChannelConfig, ChatType, TriggerMode
from watchpost.notifiers.external_plugin import ExternalCommandNotifier

_PLUGIN_NAME_RE = re.compile(r"^[a-z][a-z0-9_-]{0,48}$")


def _pascal_case(slug: str) -> str:
    parts = [p for p in re.split(r"[-_]+", slug) if p]
    return "".join(part[:1].upper() + part[1:] for part in parts) or "Custom"


def scaffold_plugin(
    *,
    kind: Literal["channel", "notifier"],
    name: str,
    dest: Path,
    force: bool = False,
) -> dict[str, Any]:
    """Generate a runnable starter plugin package using `watchpost.sdk`."""
    slug = name.strip()
    if not _PLUGIN_NAME_RE.fullmatch(slug):
        raise ValueError(
            f"Invalid plugin name {name!r}: expected lowercase [a-z][a-z0-9_-]{{0,48}}"
        )
    if kind not in {"channel", "notifier"}:
        raise ValueError(f"Unsupported plugin kind: {kind!r}")

    target_dir = Path(dest).expanduser()
    script_path = target_dir / "plugin.py"
    readme_path = target_dir / "README.md"
    if script_path.exists() and not force:
        raise FileExistsError(f"Plugin file already exists: {script_path} (pass --force to overwrite)")

    target_dir.mkdir(parents=True, exist_ok=True)
    cls_prefix = _pascal_case(slug)

    if kind == "channel":
        code = f'''#!/usr/bin/env python3
"""Watchpost channel plugin for {slug}."""

from __future__ import annotations

from watchpost.sdk import ChannelPlugin, make_chat, make_message, run_channel_plugin


class {cls_prefix}ChannelPlugin(ChannelPlugin):
    name = {slug!r}

    def list_chats(self) -> list[dict[str, str]]:
        # Replace with API/CLI discovery for your chat platform.
        return [
            make_chat("demo_room_1", "{cls_prefix} Demo Chat", chat_type="p2p"),
        ]

    def fetch_recent(self, channel: dict[str, object], limit: int = 50) -> list[dict[str, object]]:
        del channel, limit
        # Return chronological NormalizedMessage dicts created via make_message().
        return [
            make_message(
                message_id="msg_1",
                sender_id="peer_1",
                sender_name="Teammate",
                clean_text="Sample message from {slug} plugin",
                position=1,
            )
        ]


if __name__ == "__main__":
    raise SystemExit(run_channel_plugin({cls_prefix}ChannelPlugin()))
'''
        config_snippet: dict[str, Any] = {
            "external_adapters": [
                {
                    "name": slug,
                    "command": [sys.executable, str(script_path)],
                    "timeout_s": 45.0,
                    "env": {},
                }
            ]
        }
        check_cmd = f"watchpost plugins check --kind channel --test-fetch --cmd {sys.executable} {script_path}"
    else:
        code = f'''#!/usr/bin/env python3
"""Watchpost owner notifier plugin for {slug}."""

from __future__ import annotations

import sys

from watchpost.sdk import NotifierPlugin, make_owner_action, run_notifier_plugin


class {cls_prefix}NotifierPlugin(NotifierPlugin):
    name = {slug!r}

    def send_message(self, text: str) -> str:
        # Replace with your push/DM delivery API (e.g. Slack DM, ntfy, Bark, Pushover).
        print(f"[{slug} -> owner] {{text}}", file=sys.stderr)
        return ""

    def poll_actions(self) -> list[dict[str, object]]:
        # Optional: return owner replies parsed through make_owner_action().
        sample = make_owner_action("", notifier=self.name)
        return [sample] if sample is not None else []


if __name__ == "__main__":
    raise SystemExit(run_notifier_plugin({cls_prefix}NotifierPlugin()))
'''
        config_snippet = {
            "external_notifiers": [
                {
                    "name": slug,
                    "command": [sys.executable, str(script_path)],
                    "timeout_s": 30.0,
                    "env": {},
                }
            ]
        }
        check_cmd = f"watchpost plugins check --kind notifier --cmd {sys.executable} {script_path}"

    readme = f"""# Watchpost `{slug}` ({kind} plugin)

Starter external Watchpost plugin generated by `watchpost plugins scaffold`.

## Test Conformance

```bash
{check_cmd}
```

## Enable in `~/.config/watchpost/config.json`

Merge this snippet into your Watchpost config, then hot-reload (`POST /api/reload` or `SIGHUP`):

```json
{json.dumps(config_snippet, indent=2, ensure_ascii=False)}
```
"""

    script_path.write_text(code, encoding="utf-8")
    os.chmod(script_path, 0o755)
    readme_path.write_text(readme, encoding="utf-8")
    return {
        "kind": kind,
        "name": slug,
        "script_path": str(script_path),
        "readme_path": str(readme_path),
        "config_snippet": config_snippet,
    }


async def check_plugin(
    *,
    kind: Literal["channel", "notifier"],
    command: list[str],
    test_fetch: bool = False,
    timeout_s: float = 15.0,
) -> dict[str, Any]:
    """Validate an external Watchpost plugin against the stdio JSON contract."""
    checks: list[dict[str, Any]] = []
    cmd0 = command[0] if command else ""
    exe_found = bool(cmd0 and (Path(cmd0).expanduser().is_file() or shutil.which(cmd0)))
    checks.append(
        {
            "name": "executable",
            "ok": exe_found,
            "detail": cmd0 if exe_found else f"Executable not found: {cmd0 or '<empty>'}",
        }
    )
    if not exe_found:
        return {"ok": False, "kind": kind, "command": command, "checks": checks}

    if kind == "channel":
        adapter = ExternalCommandAdapter(
            ExternalAdapterConfig(name="check_channel", command=command, timeout_s=timeout_s)
        )
        try:
            health = await adapter.health()
            h_ok = bool(health.get("ok", True))
            checks.append({"name": "health", "ok": h_ok, "detail": str(health)})
        except Exception as exc:
            msg = str(exc)
            if "unknown" in msg.lower() or "unsupported" in msg.lower():
                checks.append({"name": "health", "ok": True, "detail": f"optional (not implemented): {msg}"})
            else:
                checks.append({"name": "health", "ok": False, "detail": msg})

        chats: list[dict[str, str]] = []
        try:
            chats = await adapter.list_available_chats()
            checks.append(
                {"name": "list-chats", "ok": True, "detail": f"{len(chats)} chat(s) discovered"}
            )
        except Exception as exc:
            checks.append({"name": "list-chats", "ok": False, "detail": str(exc)})

        if test_fetch and chats:
            first = chats[0]
            ct = ChatType.group if first.get("chat_type") == "group" else ChatType.p2p
            trig = TriggerMode.mention_owner if ct == ChatType.group else TriggerMode.all
            sample_ch = ChannelConfig(
                id="check_ch",
                adapter="check_channel",
                external_chat_id=first["external_chat_id"],
                name=first.get("name") or first["external_chat_id"],
                chat_type=ct,
                trigger_mode=trig,
            )
            try:
                msgs = await adapter.fetch_recent(sample_ch, limit=5)
                checks.append(
                    {
                        "name": "fetch-recent",
                        "ok": True,
                        "detail": f"validated {len(msgs)} NormalizedMessage item(s)",
                    }
                )
            except Exception as exc:
                checks.append({"name": "fetch-recent", "ok": False, "detail": str(exc)})
        elif test_fetch:
            checks.append({"name": "fetch-recent", "ok": True, "detail": "skipped (no chats returned)"})
    elif kind == "notifier":
        notifier = ExternalCommandNotifier(
            ExternalNotifierConfig(name="check_notifier", command=command, timeout_s=timeout_s)
        )
        try:
            health = await notifier.health()
            h_ok = bool(health.get("ok", True))
            checks.append({"name": "health", "ok": h_ok, "detail": str(health)})
        except Exception as exc:
            msg = str(exc)
            if "unknown" in msg.lower() or "unsupported" in msg.lower():
                checks.append({"name": "health", "ok": True, "detail": f"optional (not implemented): {msg}"})
            else:
                checks.append({"name": "health", "ok": False, "detail": msg})

        try:
            actions = await notifier.poll_owner_actions()
            checks.append(
                {
                    "name": "poll-actions",
                    "ok": True,
                    "detail": f"validated {len(actions)} OwnerAction item(s)",
                }
            )
        except Exception as exc:
            checks.append({"name": "poll-actions", "ok": False, "detail": str(exc)})
    else:
        checks.append({"name": "kind", "ok": False, "detail": f"Unsupported plugin kind: {kind!r}"})

    overall_ok = all(bool(c["ok"]) for c in checks)
    return {"ok": overall_ok, "kind": kind, "command": command, "checks": checks}
